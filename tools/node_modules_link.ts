// Generates the node_modules subrepo for a pnpm workspace, in pnpm's layout. Every
// lockfile snapshot (a package version with its peers resolved) gets one directory,
// node_modules/_store/<snapshot>/node_modules/, holding the package itself beside
// symlinks to its dependencies' directories. Each importer's node_modules/<dep> is a
// symlink into that one store. A package therefore exists once per snapshot across
// the whole workspace, so a package and its peers resolve to the same instance, and
// no target's output ever sits inside another's.
//
// The subrepo is registered with package_root set to the lockfile's directory, so
// every output lands beside the workspace's sources: node_modules/... for the root
// importer, packages/ui/node_modules/... for packages/ui. Each importer's public
// targets live in the subrepo package named after its directory.
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";
import { args, packageKey, readLockfile, snapshotKey, splitKey, type PackageInfo } from "./lockfile.ts";

const opts = args(process.argv.slice(2));
const lock = readLockfile(opts.lock);
const importerDirs = opts.importers.split(",");
for (const dir of importerDirs) {
  if (!lock.importers[dir]) {
    throw new Error(`no importer ${dir} in ${opts.lock}`);
  }
}
const cpu = opts.cpu === "amd64" ? "x64" : opts.cpu;
const STORE = "node_modules/_store";

function matches(values: string[] | undefined, want: string): boolean {
  if (!values || values.length === 0) {
    return true;
  }
  const negated = values.filter((v) => v.startsWith("!")).map((v) => v.slice(1));
  return negated.length > 0 ? !negated.includes(want) : values.includes(want);
}

function runsHere(snapKey: string): boolean {
  const info: PackageInfo | undefined = lock.packages[packageKey(snapKey)];
  if (!info) {
    throw new Error(`snapshot ${snapKey} has no package entry`);
  }
  return matches(info.os, opts.os) && matches(info.cpu, cpu) && matches(info.libc, "glibc");
}

/** The snapshot's directory: pnpm's encoding, hashed when it gets long. */
function storeDir(snapKey: string): string {
  const flat = snapKey.replace(/\//g, "+").replace(/\(/g, "_").replace(/\)/g, "");
  if (flat.length <= 100) {
    return `${STORE}/${flat}/node_modules`;
  }
  const { name, version } = splitKey(snapKey);
  const hash = createHash("sha256").update(snapKey).digest("hex").slice(0, 16);
  return `${STORE}/${name.replace(/\//g, "+")}@${version}_${hash}/node_modules`;
}

/** Each dependency of a snapshot, by the name it is imported as. */
function depsOf(snapKey: string): Array<[string, string]> {
  const snap = lock.snapshots[snapKey] ?? {};
  const out: Array<[string, string]> = [];
  for (const [deps, optional] of [[snap.dependencies, false], [snap.optionalDependencies, true]] as const) {
    for (const [name, ref] of Object.entries(deps ?? {})) {
      const key = snapshotKey(name, ref);
      if (key && (!optional || runsHere(key))) {
        out.push([name, key]);
      }
    }
  }
  return out;
}

/** A rule's Please package and target name, for a path whose last element is a package name. */
function slot(dir: string, name: string): { pkg: string; target: string } {
  const i = name.lastIndexOf("/");
  return i < 0 ? { pkg: dir, target: name } : { pkg: `${dir}/${name.slice(0, i)}`, target: name.slice(i + 1) };
}

const builds = new Map<string, string[]>();
function emit(pkg: string, rule: string): void {
  builds.set(pkg, [...(builds.get(pkg) ?? []), rule]);
}

function symlinkRule(dir: string, name: string, target: string): string {
  const { pkg, target: base } = slot(dir, name);
  emit(
    pkg,
    `genrule(
    name = ${JSON.stringify(base)},
    outs = [${JSON.stringify(base)}],
    cmd = ${JSON.stringify(`ln -s ${posix.relative(pkg, target)} "$OUT"`)},
    visibility = ["PUBLIC"],
)
`,
  );
  return `//${pkg}:${base}`;
}

/** The dependencies a snapshot links, leaving out one named like the package itself. */
function linkedDeps(snapKey: string): Array<[string, string]> {
  const own = splitKey(snapKey).name;
  return depsOf(snapKey).filter(([depName]) => depName !== own);
}

// Each reachable snapshot's directory is written once, keyed by snapshot.
const labels = new Map<string, string[]>();
function visit(snapKey: string): void {
  if (labels.has(snapKey)) {
    return;
  }
  const own: string[] = [];
  labels.set(snapKey, own);
  const dir = storeDir(snapKey);
  const { name, version } = splitKey(snapKey);
  const { pkg, target: base } = slot(dir, name);
  emit(
    pkg,
    `filegroup(
    name = ${JSON.stringify(base)},
    srcs = [${JSON.stringify(`${opts.store}//pkgs/${name}/${version}:${base}`)}],
    visibility = ["PUBLIC"],
)
`,
  );
  own.push(`//${pkg}:${base}`);
  for (const [depName, depKey] of linkedDeps(snapKey)) {
    own.push(symlinkRule(dir, depName, `${storeDir(depKey)}/${splitKey(depKey).name}`));
    visit(depKey);
  }
}

function closureKeys(snapKey: string): string[] {
  const seen = new Set<string>();
  const stack = [snapKey];
  while (stack.length > 0) {
    const key = stack.pop()!;
    if (seen.has(key)) continue;
    seen.add(key);
    stack.push(...linkedDeps(key).map(([, depKey]) => depKey));
  }
  return [...seen];
}

// Builds see the closure through exported_deps; tests see it through runtime_deps,
// which only a binary target may carry.
function publicTarget(name: string, deps: string[]): string {
  const list = deps.map((d) => `        ${JSON.stringify(d)},`).join("\n");
  return `filegroup(
    name = ${JSON.stringify(name)},
    binary = True,
    exported_deps = [
${list}
    ],
    runtime_deps = [
${list}
    ],
    visibility = ["PUBLIC"],
)
`;
}

function directDeps(dir: string): Array<[string, { version: string }]> {
  const importer = lock.importers[dir];
  return [importer.dependencies, importer.devDependencies, importer.optionalDependencies]
    .flatMap((group) => Object.entries(group ?? {}))
    .sort((a, b) => a[0].localeCompare(b[0]));
}

// pnpm's hidden hoisting: one version of every package, linked where the walk up
// from any store directory finds it. Packages that import what they don't declare
// (tiptap-markdown imports @tiptap/pm) resolve through it. The root importer's
// packages win, then shallower ones.
const hoisted = new Map<string, string>();
const queue = importerDirs
  .flatMap((dir) => directDeps(dir))
  .map(([name, { version }]) => (version.startsWith("link:") ? undefined : snapshotKey(name, version)))
  .filter((key): key is string => key !== undefined && runsHere(key));
for (let key = queue.shift(); key !== undefined; key = queue.shift()) {
  const name = splitKey(key).name;
  if (hoisted.has(name)) continue;
  hoisted.set(name, key);
  queue.push(...linkedDeps(key).map(([, depKey]) => depKey));
}
const hoistLabel = new Map<string, string>();
for (const [name, key] of hoisted) {
  visit(key);
  hoistLabel.set(name, symlinkRule(`${STORE}/node_modules`, name, `${storeDir(key)}/${name}`));
}

let directCount = 0;
let linked = 0;
for (const dir of importerDirs) {
  const pkgDir = dir === "." ? "" : dir;
  const top = posix.join(pkgDir, "node_modules");
  const publics: string[] = [];
  const everything = new Set<string>();
  for (const [name, { version }] of directDeps(dir)) {
    let deps: string[];
    let names: string[] = [];
    if (version.startsWith("link:")) {
      // A workspace package is a symlink to its directory, as pnpm makes it, so its
      // files resolve their own imports from its importer's node_modules.
      deps = [symlinkRule(top, name, posix.join(pkgDir, version.slice("link:".length)))];
      linked++;
    } else {
      const key = snapshotKey(name, version)!;
      if (!runsHere(key)) {
        continue;
      }
      visit(key);
      const keys = closureKeys(key);
      names = keys.map((k) => splitKey(k).name);
      deps = [symlinkRule(top, name, `${storeDir(key)}/${splitKey(key).name}`), ...keys.flatMap((k) => labels.get(k)!)];
    }
    // A dependency's own target carries the hoisted links for its closure only, so
    // an undeclared import of a package outside it still needs :everything.
    deps.push(...names.flatMap((n) => hoistLabel.get(n) ?? []));
    deps = [...new Set(deps)].sort();
    deps.forEach((d) => everything.add(d));
    publics.push(publicTarget(name.replace(/^@/, "").replace(/\//g, "_"), deps));
    directCount++;
  }
  hoistLabel.forEach((l) => everything.add(l));
  publics.push(publicTarget("everything", [...everything].sort()));
  emit(pkgDir, publics.join("\n"));
}

for (const [dir, rules] of builds) {
  mkdirSync(join(opts.out, dir), { recursive: true });
  writeFileSync(join(opts.out, dir, "BUILD"), rules.join("\n"));
}
console.error(
  `node_modules_link: ${labels.size} snapshots, ${importerDirs.length} importers, ${directCount} direct deps (${linked} workspace links)`,
);
