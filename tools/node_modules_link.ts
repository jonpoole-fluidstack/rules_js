// Generates the node_modules subrepo for one importer. It lays the importer's
// dependency closure out as a hoisted node_modules tree (npm's flat layout, nesting
// only on a version conflict) and writes one filegroup per placed package, in a
// subrepo package that mirrors the package's place in the tree. The subrepo is
// registered with package_root set to the importer's directory, so each filegroup's
// output lands at <importer>/node_modules/... beside the importer's sources.
import { mkdirSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";
import { args, packageKey, readLockfile, snapshotKey, splitKey, type PackageInfo } from "./lockfile.ts";

const opts = args(process.argv.slice(2));
const lock = readLockfile(opts.lock);
const importer = lock.importers[opts.importer];
if (!importer) {
  throw new Error(`no importer ${opts.importer} in ${opts.lock}`);
}
const cpu = opts.cpu === "amd64" ? "x64" : opts.cpu;

function matches(values: string[] | undefined, want: string): boolean {
  if (!values || values.length === 0) {
    return true;
  }
  const negated = values.filter((v) => v.startsWith("!")).map((v) => v.slice(1));
  return negated.length > 0 ? !negated.includes(want) : values.includes(want);
}

function runsHere(info: PackageInfo): boolean {
  return matches(info.os, opts.os) && matches(info.cpu, cpu) && matches(info.libc, "glibc");
}

/** A package at one place in the tree, e.g. node_modules/vite/node_modules/esbuild. */
interface Placement {
  path: string;
  name: string;
  snapKey: string;
  deps: string[];
  /** For a workspace package (`link:`), its directory relative to the importer. */
  link?: string;
}

const ROOT = "node_modules";
const placements = new Map<string, Placement>();
const dirs = new Map<string, Map<string, string>>();
const queue: Placement[] = [];

function place(dir: string, name: string, snapKey: string): Placement {
  if (!dirs.has(dir)) {
    dirs.set(dir, new Map());
  }
  dirs.get(dir)!.set(name, snapKey);
  const p: Placement = { path: `${dir}/${name}`, name, snapKey, deps: [] };
  placements.set(p.path, p);
  queue.push(p);
  return p;
}

/** The node_modules directories node searches from a package, nearest first. */
function lookupChain(path: string): string[] {
  const containing = (p: string) => p.slice(0, p.lastIndexOf("node_modules/") + "node_modules".length);
  const chain = [`${path}/node_modules`];
  for (let dir = containing(path); ; dir = containing(dir.slice(0, -"/node_modules".length))) {
    chain.push(dir);
    if (dir === ROOT) {
      return chain;
    }
  }
}

function depsOf(snapKey: string): Array<[string, string]> {
  const snap = lock.snapshots[snapKey] ?? {};
  const out: Array<[string, string]> = [];
  for (const [name, ref] of Object.entries(snap.dependencies ?? {})) {
    const key = snapshotKey(name, ref);
    if (key) out.push([name, key]);
  }
  for (const [name, ref] of Object.entries(snap.optionalDependencies ?? {})) {
    const key = snapshotKey(name, ref);
    if (key && runsHere(lock.packages[packageKey(key)])) out.push([name, key]);
  }
  return out;
}

const direct: Array<[string, Placement]> = [];
for (const group of [importer.dependencies, importer.devDependencies, importer.optionalDependencies]) {
  for (const [name, { version }] of Object.entries(group ?? {})) {
    // A workspace package is a symlink to its directory, as pnpm makes it, so its
    // files resolve their own imports from its importer's node_modules.
    if (version.startsWith("link:")) {
      const p: Placement = { path: `${ROOT}/${name}`, name, snapKey: version, deps: [], link: version.slice("link:".length) };
      placements.set(p.path, p);
      dirs.set(ROOT, (dirs.get(ROOT) ?? new Map()).set(name, version));
      direct.push([name, p]);
      continue;
    }
    const key = snapshotKey(name, version);
    if (key && runsHere(lock.packages[packageKey(key)])) {
      direct.push([name, place(ROOT, name, key)]);
    }
  }
}

// Breadth first, so shallower packages claim the root slot before deeper ones.
while (queue.length > 0) {
  const p = queue.shift()!;
  const chain = lookupChain(p.path);
  for (const [name, key] of depsOf(p.snapKey)) {
    const found = chain.find((dir) => dirs.get(dir)?.has(name));
    let target: string;
    if (found && dirs.get(found)!.get(name) === key) {
      target = `${found}/${name}`;
    } else if (found) {
      target = place(chain[0], name, key).path;
    } else {
      target = place(ROOT, name, key).path;
    }
    p.deps.push(target);
  }
}

function label(path: string): string {
  const i = path.lastIndexOf("/");
  return `//${path.slice(0, i)}:${path.slice(i + 1)}`;
}

function closure(start: string): string[] {
  const seen = new Set<string>();
  const stack = [start];
  while (stack.length > 0) {
    const path = stack.pop()!;
    if (seen.has(path)) continue;
    seen.add(path);
    stack.push(...placements.get(path)!.deps);
  }
  return [...seen].sort();
}

function storeLabel(p: Placement): string {
  const { name, version } = splitKey(p.snapKey);
  return `${opts.store}//pkgs/${name}/${version}:${name.split("/").pop()}`;
}

/** The top-level placement whose directory holds this one: node_modules/<name>. */
function owner(path: string): string {
  const rest = path.slice(`${ROOT}/`.length).split("/");
  return `${ROOT}/${rest.slice(0, rest[0].startsWith("@") ? 2 : 1).join("/")}`;
}

// A package nested in another's node_modules would be an output inside another
// target's output directory, and Please replaces a directory output wholesale when it
// writes it. So every nested placement is copied into its top-level owner instead, and
// only top-level packages are targets.
const nestedIn = new Map<string, Placement[]>();
for (const p of placements.values()) {
  const top = owner(p.path);
  if (top !== p.path) {
    nestedIn.set(top, [...(nestedIn.get(top) ?? []), p]);
  }
}

// A scoped package's target lives in a subrepo package for its scope, so its output
// is named by the part after the slash.
const builds = new Map<string, string[]>();
for (const p of placements.values()) {
  if (owner(p.path) !== p.path) {
    continue;
  }
  const i = p.path.lastIndexOf("/");
  const pkgDir = p.path.slice(0, i);
  const base = p.path.slice(i + 1);
  const nested = (nestedIn.get(p.path) ?? []).sort((a, b) => a.path.length - b.path.length);
  let rule: string;
  if (p.link !== undefined) {
    rule = `genrule(
    name = ${JSON.stringify(base)},
    outs = [${JSON.stringify(base)}],
    cmd = ${JSON.stringify(`ln -s ${posix.relative(pkgDir, p.link)} "$OUT"`)},
    visibility = ["PUBLIC"],
)
`;
  } else if (nested.length === 0) {
    rule = `filegroup(
    name = ${JSON.stringify(base)},
    srcs = [${JSON.stringify(storeLabel(p))}],
    visibility = ["PUBLIC"],
)
`;
  } else {
    // Shallower paths first, so a nested package's own node_modules exists before its children land in it.
    const srcs = [`        "pkg": [${JSON.stringify(storeLabel(p))}],`];
    const cmds = ['cp -R "$SRCS_PKG" "$OUT"', 'chmod -R u+w "$OUT"'];
    nested.forEach((n, k) => {
      const rel = n.path.slice(p.path.length + 1);
      srcs.push(`        "n${k}": [${JSON.stringify(storeLabel(n))}],`);
      cmds.push(`mkdir -p "$OUT/${rel.slice(0, rel.lastIndexOf("/"))}"`, `cp -R "$SRCS_N${k}" "$OUT/${rel}"`);
    });
    rule = `genrule(
    name = ${JSON.stringify(base)},
    srcs = {
${srcs.join("\n")}
    },
    outs = [${JSON.stringify(base)}],
    cmd = ${JSON.stringify(cmds.join(" && "))},
    visibility = ["PUBLIC"],
)
`;
  }
  builds.set(pkgDir, [...(builds.get(pkgDir) ?? []), rule]);
}

// The public targets carry no files of their own: each exports the placements of its
// package's whole closure. Placements have no deps, so cycles in the npm graph never
// become cycles in the build graph.
const publics: string[] = [];
for (const [name, p] of direct.sort((a, b) => a[0].localeCompare(b[0]))) {
  const target = name.replace(/^@/, "").replace(/\//g, "_");
  const deps = [...new Set(closure(p.path).map((path) => label(owner(path))))]
    .map((l) => `        ${JSON.stringify(l)},`)
    .join("\n");
  publics.push(`filegroup(
    name = ${JSON.stringify(target)},
    exported_deps = [
${deps}
    ],
    visibility = ["PUBLIC"],
)
`);
}
const everything = [...new Set(direct.flatMap(([, p]) => closure(p.path).map((path) => label(owner(path)))))].sort();
publics.push(`filegroup(
    name = "everything",
    exported_deps = [
${everything.map((l) => `        ${JSON.stringify(l)},`).join("\n")}
    ],
    visibility = ["PUBLIC"],
)
`);
builds.set("", publics);

for (const [dir, rules] of builds) {
  mkdirSync(join(opts.out, dir), { recursive: true });
  writeFileSync(join(opts.out, dir, "BUILD"), rules.join("\n"));
}

const nested = [...placements.keys()].filter((path) => path.indexOf("/node_modules/") > 0);
console.error(
  `node_modules_link: ${placements.size} placements, ${direct.length} direct deps, ${nested.length} nested: ${nested.join(", ") || "none"}`,
);
